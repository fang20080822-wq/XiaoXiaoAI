import assert from "node:assert/strict";
import {hashPassword,verifyPassword,createSessionToken,hashSessionToken,sessionExpiry,requireRole} from "../lib/auth.js";
import {containsPII,validateAlias,parseDataTable,scoreRecord,offlineAnswer} from "../lib/inquiry.js";
const p=hashPassword("a-secure-test-password");
assert.equal(p.iterations,210000);
assert.equal(verifyPassword("a-secure-test-password",p.salt,p.hash),true);
assert.equal(verifyPassword("wrong-password",p.salt,p.hash),false);
const token=createSessionToken();
assert.ok(token.length>=40);
assert.notEqual(token,hashSessionToken(token));
assert.equal(sessionExpiry("teacher").getTime()-Date.now()<=8*60*60*1000,true);
assert.equal(sessionExpiry("student").getTime()-Date.now()<=24*60*60*1000,true);
let roleNext=false,roleStatus=0;
const roleReq={headers:{authorization:"Bearer opaque-test-token"},app:{locals:{db:{query:async()=>({rowCount:1,rows:[{role:"teacher",subject_id:"teacher-1",expires_at:new Date()}]})}}}};
const roleRes={status(code){roleStatus=code;return this;},json(){return this;}};
await requireRole("teacher")(roleReq,roleRes,()=>{roleNext=true;});
assert.equal(roleNext,true);
roleNext=false;roleStatus=0;
await requireRole("student")(roleReq,roleRes,()=>{roleNext=true;});
assert.equal(roleNext,false);
assert.equal(roleStatus,401);
assert.equal(containsPII("13800138000"),true);
assert.equal(containsPII("student-A"),false);
assert.equal(validateAlias("学生A").valid,true);
assert.equal(validateAlias("三年级一班").valid,false);
assert.equal(validateAlias("12345678").valid,false);
assert.equal(validateAlias("wxid_ab12").valid,false);
assert.equal(parseDataTable("第1次|10:00|12|cm\n第2次|10:05|13|cm").valid,true);
assert.equal(parseDataTable("第1次|10:00|十二|cm\n第2次|10:05|13|cm").valid,false);
assert.equal(parseDataTable("第1次|10:00||cm\n第2次|10:05|13|cm").valid,false);
assert.equal(scoreRecord({topic:"植物",question:"问题",dataTable:"第1次|10:00|12|cm\n第2次|10:05|13|cm"}).level>=1,true);
assert.match(offlineAnswer("怎样点燃汽油做实验"),/危险|不要尝试/);
assert.match(offlineAnswer("怎样用漂白剂和盐酸做实验？"),/可能有危险/);
assert.match(offlineAnswer("怎样用电池短路发热？"),/可能有危险/);
console.log("V5.7 helper tests passed.");
